//! Turns the gathered [`Message`]s into `CodeGeneratorResponse` files.
//!
//! One Rust file per proto *package*, `<package>.defaults.rs`, plus the module
//! tree that mounts them. Per package rather than per source `.proto` to match
//! `protoc-gen-buffa` under `file_per_package=true`, which is what a consumer
//! of both ends up with: `example.v1.rs` and `example.v1.defaults.rs`, side by
//! side and includable into the same module. The `.defaults` says which plugin
//! wrote it, so several extending the same package can share a directory.

mod field;
mod oneof;

use std::collections::BTreeMap;

use anyhow::{Context, Result, anyhow};
use buffa_codegen::generated::compiler::code_generator_response::File;
use proc_macro2::{Literal, TokenStream};
use quote::{format_ident, quote};

use crate::messages::{Item, Message, Method};

/// The header on every emitted file.
const HEADER: &str = "// @generated by protoc-gen-rust-defaults. DO NOT EDIT.\n";

/// Plugin options, parsed from `opt:` in `buf.gen.yaml`.
#[derive(Debug, Clone)]
pub struct Options {
    /// The Rust module the buffa-generated message types live under.
    ///
    /// Each leaf of the emitted module tree does `use <proto_module>::<pkg>::*`
    /// so the methods emitted for a message can name it unqualified, and a
    /// type from another package is named from here. Read only when
    /// [`packaging`](Self::packaging) is on, since that tree is the only
    /// thing it appears in.
    pub proto_module: String,

    /// Whether to emit the module tree that mounts the per-package output:
    /// `mod.rs`.
    ///
    /// On by default, which is what a consumer mounting the whole tree with
    /// `include!("defaults/mod.rs")` needs.
    ///
    /// Off for a consumer that instead includes the per-package output into
    /// the module already holding the message types. Then the packaging file
    /// is not merely unused -- a `mod.rs` written into the same directory as a
    /// hand-written one silently replaces it, which `buf generate` reports as
    /// success.
    pub packaging: bool,

    /// `extern_path` entries, as `protoc-gen-buffa` takes them: `.pkg=::path`.
    ///
    /// The same ones the consumer passes to buffa, so an enum this plugin names
    /// is named where buffa put it. Well-known types need none; they resolve to
    /// `buffa-types` as they do in buffa.
    pub extern_paths: Vec<(String, String)>,

    /// A trait with a `fn set_defaults(&mut self)` to implement for every
    /// message that gets a generated `set_defaults`, by calling it.
    ///
    /// Unset by default, and then the output is inherent methods and nothing
    /// else: no dependency, and nothing a consumer has to name. Set it to code
    /// against messages generically -- an interceptor that defaults whatever
    /// request it is handed -- with a trait the consumer owns.
    ///
    /// An `unexported` message gets no impl, since its `set_defaults` is the
    /// hand-written one and so is its impl of the trait.
    pub impl_trait: Option<String>,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            proto_module: "crate::proto".to_owned(),
            packaging: true,
            extern_paths: Vec::new(),
            impl_trait: None,
        }
    }
}

/// Renders the response files for `messages`.
///
/// One `<package>.defaults.rs` per proto package with a message in it, plus --
/// unless [`Options::packaging`] is off -- the `mod.rs` that mounts them. A
/// schema with no defaults produces no output at all, rather than an empty file
/// the consumer would still have to mount.
///
/// # Errors
///
/// If emitted tokens do not parse as Rust -- which is a bug in this crate,
/// reported with the tokens -- or if `proto_module` or `impl_trait` is not a
/// Rust path.
pub fn render(messages: &[Message], options: &Options) -> Result<Vec<File>> {
    let impl_trait = options
        .impl_trait
        .as_deref()
        .map(|path| {
            syn::parse_str::<syn::Path>(path)
                .with_context(|| format!("impl_trait {path:?} is not a Rust path"))
        })
        .transpose()?;

    // Proto package to its messages' methods, in the order they were
    // gathered, so the output is stable across runs.
    let mut by_package: BTreeMap<&str, Vec<TokenStream>> = BTreeMap::new();
    for message in messages {
        by_package
            .entry(message.package.as_str())
            .or_default()
            .push(message_tokens(message, impl_trait.as_ref())?);
    }

    let mut files = Vec::new();
    for (package, bodies) in &by_package {
        let path = package_file(package);
        let content = format(
            &quote! {
                // Brings the buffa message types into scope: mounted by the
                // module tree, or already present in the module a consumer
                // included this into.
                #[allow(unused_imports, clippy::wildcard_imports)]
                use super::*;
                #( #bodies )*
            },
            &path,
        )?;
        files.push(file(path, content));
    }

    if files.is_empty() || !options.packaging {
        return Ok(files);
    }

    files.push(file(
        "mod.rs".to_owned(),
        module_tree(by_package.keys().copied(), options)?,
    ));
    Ok(files)
}

/// The inherent method for `message`, and for an exported one an impl of
/// `impl_trait`, if given, that calls it.
fn message_tokens(message: &Message, impl_trait: Option<&syn::Path>) -> Result<TokenStream> {
    let path = parse_path(&message.path)?;
    let mut body = Vec::new();
    for item in &message.items {
        body.push(match item {
            Item::Field(field) => field::emit(field)?,
            Item::Oneof(oneof) => oneof::emit(oneof)?,
        });
    }

    // The length of a method is the length of the schema's message, which
    // `clippy::too_many_lines` in the consumer has no business with.
    let lints = if message.items.iter().any(|item| match item {
        Item::Oneof(oneof) => oneof::creates_default(oneof),
        Item::Field(_) => false,
    }) {
        quote! { #[allow(clippy::too_many_lines, clippy::default_trait_access)] }
    } else {
        quote! { #[allow(clippy::too_many_lines)] }
    };

    let fqn = &message.fqn;
    Ok(match message.method {
        Method::SetDefaults => {
            let docs = doc(&format!(
                "Fills each unset field of `{fqn}` with its \
                 `(protoc_contrib.defaults.value)`.\n\n\
                 A field that is already set is left as it is."
            ));
            // `Self::set_defaults` names the inherent method, which takes
            // precedence over the trait's of the same name.
            let impl_trait = impl_trait.map(|impl_trait| {
                quote! {
                    impl #impl_trait for #path {
                        fn set_defaults(&mut self) {
                            Self::set_defaults(self);
                        }
                    }
                }
            });
            quote! {
                impl #path {
                    #docs
                    #lints
                    pub fn set_defaults(&mut self) {
                        #( #body )*
                    }
                }
                #impl_trait
            }
        }
        Method::ApplyDefaults => {
            let docs = doc(&format!(
                "Fills each unset field of `{fqn}` with its \
                 `(protoc_contrib.defaults.value)`.\n\n\
                 Generated in place of `set_defaults`, because the message is \
                 `(protoc_contrib.defaults.unexported)`: a hand-written \
                 `set_defaults` calls this and adds its own logic."
            ));
            quote! {
                impl #path {
                    #docs
                    #lints
                    pub(crate) fn apply_defaults(&mut self) {
                        #( #body )*
                    }
                }
            }
        }
    })
}

/// The file a package's output is written to.
///
/// One per package, so the module tree includes it directly and there is no
/// intermediate `<package>.mod.rs` between the two.
fn package_file(package: &str) -> String {
    format!("{package}.defaults.rs")
}

fn file(name: String, content: String) -> File {
    File {
        name: Some(name),
        content: Some(content),
        insertion_point: None,
        generated_code_info: None.into(),
        ..Default::default()
    }
}

/// Parses `tokens` as a Rust file and renders it, so the output is readable
/// rather than one line of `TokenStream`.
fn format(tokens: &TokenStream, label: &str) -> Result<String> {
    let parsed: syn::File = syn::parse2(tokens.clone()).map_err(|error| {
        // The tokens go into the message because this failing means the
        // generator emitted something ill-formed, and the tokens are the only
        // evidence of what.
        anyhow!(
            "emitted tokens for {label} do not parse: {error}\n\
             --- BEGIN TOKENS ---\n{tokens}\n--- END TOKENS ---"
        )
    })?;
    Ok(format!("{HEADER}{}", prettyplease::unparse(&parsed)))
}

/// A Rust path, as buffa's type resolution spells it, as tokens.
fn parse_path(path: &str) -> Result<TokenStream> {
    let path: syn::Path =
        syn::parse_str(path).with_context(|| format!("{path:?} is not a Rust path"))?;
    Ok(quote! { #path })
}

/// Renders `text` as a doc comment.
///
/// Emitted as `#[doc = "..."]` per line rather than as `///`, which a
/// `TokenStream` has no way to spell.
fn doc(text: &str) -> TokenStream {
    let lines: Vec<TokenStream> = text
        .lines()
        .map(|line| {
            let line = Literal::string(&if line.is_empty() {
                String::new()
            } else {
                format!(" {line}")
            });
            quote! { #[doc = #line] }
        })
        .collect();
    quote! { #( #lines )* }
}

/// One node of the proto-package trie the module tree mirrors.
#[derive(Default)]
struct Node {
    children: BTreeMap<String, Self>,
    /// Set when a package's own file is mounted at this node.
    package: Option<String>,
}

/// The top-level `mod.rs`: nested `pub mod` blocks mirroring each proto
/// package, each leaf pulling in that package's file and bringing the matching
/// buffa module into scope so the emitted `impl` blocks resolve their message
/// types by short name.
fn module_tree<'a>(packages: impl Iterator<Item = &'a str>, options: &Options) -> Result<String> {
    let mut root = Node::default();
    for package in packages {
        let mut node = &mut root;
        for segment in package.split('.').filter(|s| !s.is_empty()) {
            node = node.children.entry(segment.to_owned()).or_default();
        }
        node.package = Some(package.to_owned());
    }

    let proto_module: syn::Path = syn::parse_str(&options.proto_module)
        .with_context(|| format!("proto_module {:?} is not a Rust path", options.proto_module))?;
    // Outer attributes only, never a file-level `#![allow(..)]`: a consumer
    // that mounts this with `include!` rather than `#[path]` cannot carry inner
    // attributes through the macro expansion, and which of the two they use is
    // not this plugin's business.
    let body = node_tokens(&root, &[], &proto_module);
    format(&body, "mod.rs")
}

fn node_tokens(node: &Node, path: &[&str], proto_module: &syn::Path) -> TokenStream {
    let leaf = node
        .package
        .as_ref()
        .map_or_else(TokenStream::new, |package| {
            let segments: Vec<syn::Ident> = path
                .iter()
                .map(|s| format_ident!("{}", buffa_codegen::idents::escape_mod_ident(s)))
                .collect();
            let include = Literal::string(&package_file(package));
            // Terse `allow`s, without the `reason` this crate writes for itself:
            // this file is machine-generated and read at a glance, and a paragraph
            // above every `use` buries the three lines that carry information.
            quote! {
                #[allow(unused_imports, clippy::wildcard_imports)]
                use #proto_module #( :: #segments )* ::*;
                include!(#include);
            }
        });
    let children: Vec<TokenStream> = node
        .children
        .iter()
        .map(|(segment, child)| {
            let ident = format_ident!("{}", buffa_codegen::idents::escape_mod_ident(segment));
            let mut next = path.to_vec();
            next.push(segment);
            let inner = node_tokens(child, &next, proto_module);
            quote! {
                #[allow(clippy::module_inception)]
                pub mod #ident {
                    #[allow(unused_imports, clippy::wildcard_imports)]
                    use super::*;
                    #inner
                }
            }
        })
        .collect();
    quote! {
        #leaf
        #( #children )*
    }
}
